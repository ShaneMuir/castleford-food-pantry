import { chromium } from "@playwright/test";
const out = ".screenshots/";
const b = await chromium.launch();
const p = await (await b.newContext({ viewport: { width: 390, height: 844 }, ignoreHTTPSErrors: true })).newPage();
await p.goto("https://castleford-food-pantry.test/", { waitUntil: "networkidle" });
await p.addStyleTag({ content: "html{scroll-behavior:auto!important}" });
await p.evaluate(() => scrollTo(0, 0));
await p.waitForTimeout(500);
await p.screenshot({ path: out + "v5-mobile-top.png" });
const btn = p.getByRole("button", { name: /open menu/i });
console.log("menu button visible:", await btn.isVisible());
await btn.click();
await p.waitForTimeout(500);
await p.screenshot({ path: out + "v5-mobile-menu.png" });
await p.keyboard.press("Escape");
await p.evaluate(() => document.querySelector("#get-help").scrollIntoView());
await p.waitForTimeout(400);
await p.screenshot({ path: out + "v5-mobile-help.png" });
await b.close();
